-- # ====================================================================================
-- # EXPLAIN ANALYZE の結果の比較 (社員 10 万人、給与改定履歴 30 万件)
-- # ====================================================================================
-- 結論: このデータでは 03 (ROW_NUMBER) のほうが速く、01 (GROUP BY + JOIN) の約 6 割の時間で終わった。
--    - 全体の時間 (最後の Sort: e.id の終了時刻): 01 は約 323 ms、03 は約 186 ms
--    - MySQL の見積もりコスト (cost): 01 は 350,991、03 は 44,236
--
-- 1. 01 (GROUP BY + JOIN) で時間がかかった段階
--    - インデックスをたどって 30 万行を読む: 約 111 ms
--      effective_from はインデックスに入っていないので、1 行ずつ本体の行を取りに行っている
--    - GROUP BY で 10 万行にまとめる: 約 12 ms
--    - 給与改定履歴をもう一度引く: 約 118 ms
--      社員ごとにインデックスで 3 行ずつ引く処理を、10 万回 (loops=100000) 繰り返している
--    - 社員テーブルとの結合と最後のソート: 約 50 ms
--
-- 2. 03 (ROW_NUMBER) で時間がかかった段階
--    - 30 万行を先頭から順に読む: 約 40 ms (インデックスは使わない)
--    - 番号を振るために 30 万行を並べ替える: 約 40 ms
--    - 番号を振り、rn = 1 に絞る (30 万行 → 10 万行): 約 55 ms
--    - 社員テーブルとの結合と最後のソート: 約 50 ms
--
-- 3. 読み取れること
--    - 01 の時間の大半は、給与改定履歴を 2 回読むことにかかっている。この 2 つで約 230 ms
--    - 03 の 30 万行のソートは約 40 ms で済み、テーブルを読む時間も 01 の半分以下だった
--    - EXPLAIN では「01 は読む回数が多いがソートが少ない、03 は読む回数が少ないがソートが多い」というトレードオフに見えたが、
--      実測では読む回数が少ない 03 のほうが速かった
--
-- 4. 見積もりと実際の行数
--    - 01 の GROUP BY の結果: 見積もり 100,300 行、実際 100,000 行 (ほぼ正確)
--    - 03 の rn = 1 の絞り込み: 見積もり 29,989 行、実際 100,000 行 (約 3 倍ずれている)
--
-- 5. 注意点
--    - 1 回だけの計測で、データはすべてメモリ (バッファプール 2G) に載っている
--      ディスクから読む状況や、件数をさらに増やした場合は、差が変わる可能性がある
--    - (employee_id, effective_from) の複合インデックスがあれば、01 の 2 回の読み込みと 03 のソートの両方が軽くなる見込み
--      どちらが速くなるかは、インデックスを足して測り直さないと分からない
