-- # ====================================================================================
-- # EXPLAIN の結果の比較 (社員 10 万人、給与改定履歴 30 万件)
-- # ====================================================================================
-- 結論: EXPLAIN の結果だけでは、どちらが効率的かは決められない。
--
-- 1. 実行計画の違い
--    - 給与改定履歴を読む回数: 01 は 2 回、03 は 1 回
--    - インデックス: 01 は外部キーのインデックス (fk_salary_histories_employee) を使う
--      03 は使わない (type が ALL の全件読み込み)
--    - ソート (Using filesort): 01 は 1 回、03 は 2 回
--
-- 2. 読み取れること
--    - 01 は、GROUP BY でインデックスの並び順をそのまま使えるので、ソートが要らない
--      2 回目は、社員ごとにインデックスで該当する行だけを引いている (type が ref)
--    - 03 は、給与改定履歴を 1 回しか読まないが、番号を振るために全行を「社員 ID、給与改定日の新しい順」に並べ替える
--      この並び順に合うインデックスがないため、全件を読んでソートするしかない
--    - つまり、01 は「読む回数が多いがソートが少ない」、03 は「読む回数が少ないがソートが多い」というトレードオフになっている
--    - 実行計画の形は、23 行の小さいデータのときと同じだった。変わったのは見積もりの行数 (rows) だけ
--
-- 3. 見積もりのずれ
--    - 01 の <derived2> (GROUP BY の結果) は 299,886 行と見積もられているが、実際は社員の数と同じ 10 万行になる
--    - 03 の rn = 1 の絞り込みは、filtered が 10% (約 3 万行) と見積もられているが、実際は 10 万行が残る
--      ウィンドウ関数の結果での絞り込みは、MySQL が中身を見ずに決まった割合で見積もっているため
--
-- 4. どちらが効率的か
--    - EXPLAIN は「どう実行するつもりか」の見積もりで、実際にかかった時間は分からない。見積もり自体も実際と約 3 倍ずれている
--    - 実際の差は、補助クエリの EXPLAIN ANALYZE で測る (結果の比較はファイル末尾)


