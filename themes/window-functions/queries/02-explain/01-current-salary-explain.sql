-- 2. 01-latest-per-group/03-current-salary-with-window.sql (ROW_NUMBER) の実測
EXPLAIN ANALYZE
WITH ranked AS (
    SELECT
        sh.employee_id,
        sh.monthly_salary,
        sh.effective_from,
        ROW_NUMBER() OVER (
            PARTITION BY sh.employee_id
            ORDER BY sh.effective_from DESC
