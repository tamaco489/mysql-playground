-- 社員ごとの現在の月給を求めるクエリ例。
-- ROW_NUMBER で社員ごとに新しい給与改定日から番号を振り、番号が 1 の行だけを残す。
-- 比べる相手: 01-current-salary-without-window.sql
--
-- 01-current-salary-without-window.sql との違い
--    - 結果は同じ。11 名とも、月給と給与改定日が一致する
--    - 01 は、(1) GROUP BY で社員ごとの最新の給与改定日を求め、(2) 給与改定履歴をもう一度読んで、その給与改定日の行を取り出す
--    - 03 は、給与改定履歴を 1 回読んで各行に番号を振り、番号が 1 の行を残すだけ
--    - 01 の (1) には給与改定日しか残らないため、月給を取り出すのに給与改定履歴との JOIN がもう一度必要になる
--      03 は番号を振っても元の行の列 (月給など) がそのまま残るので、その JOIN が要らない
--    - ただし、同じ社員に同じ給与改定日の行が 2 つ以上あると、結果が変わる
--      01 はその行をすべて返し、03 は 1 行だけを返す (今のデータにはそういう行がないため、結果は同じになる)
--
-- ウィンドウ関数の結果は WHERE で直接使えないため、CTE で包んでから外側で絞る。

USE window_functions;

-- (1) 社員ごとに、新しい給与改定日から番号を振る
WITH ranked AS (
    SELECT
        sh.employee_id,
        sh.monthly_salary,
        sh.effective_from,
        ROW_NUMBER() OVER (
            PARTITION BY sh.employee_id      -- 社員ごとに番号を振り直す
            ORDER BY sh.effective_from DESC  -- 新しい給与改定日から 1, 2, 3 ... と振る
        ) AS rn
    FROM salary_histories AS sh
)
-- (2) 番号が 1 の行 (最新の給与改定日の行) だけを残す
SELECT
    e.id,
    e.name,
    r.monthly_salary,
    r.effective_from
FROM ranked AS r
INNER JOIN employees AS e
    ON e.id = r.employee_id
WHERE r.rn = 1
ORDER BY e.id;
