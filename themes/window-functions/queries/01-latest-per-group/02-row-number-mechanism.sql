-- 4. PARTITION BY の代わりに OVER の中の ORDER BY に社員 ID を足しても、社員ごとに番号は振り直されない
--    - 社員 ID 順、同じ社員の中では給与改定日の新しい順に並べたうえで、全行を通して 1〜23 の番号が振られる
--    - 結果は社員ごとにまとまって並ぶが、番号は前の社員から続いている
--      (例: 鈴木の最新の給与改定日 2026-04-01 は 1 ではなく 4、田中の 2026-04-01 は 9 になる)
--    - ORDER BY が決めるのは番号を振る順番だけで、どこで番号を 1 に戻すかは決めない
--    - 社員ごとに 1 から番号を振り直すには、ORDER BY ではなく PARTITION BY で単位を指定する必要がある
SELECT
    sh.employee_id,
    e.name,
    sh.monthly_salary,
    sh.effective_from,
    ROW_NUMBER() OVER (
        ORDER BY sh.employee_id, sh.effective_from DESC
    ) AS rn
FROM salary_histories AS sh
INNER JOIN employees AS e
    ON e.id = sh.employee_id
ORDER BY rn;
