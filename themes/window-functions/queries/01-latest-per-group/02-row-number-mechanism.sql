-- ROW_NUMBER で振った番号を、絞り込む前に見るクエリ例。
-- 社員 (PARTITION BY) ごとに effective_from (改定後の月給適用日) の新しい順 (ORDER BY) に 1, 2, 3 ... と振られる。
-- 03-current-salary-with-window.sql は、この番号が 1 の行だけを残す。

-- 1. ROW_NUMBER() について
--    - 行に 1 から順に連番を振る関数
--    - 同じ値の行があっても、必ず別々の番号を振る (番号は重複しない)
-- 2. OVER について
--    - ROW_NUMBER() などを、ウィンドウ関数として使うための句
--    - どの範囲 (PARTITION BY) で、どの順番 (ORDER BY) に番号を振るかを、括弧の中で指定する
--    - GROUP BY と違って行をまとめない。元の行数のまま、各行に番号が付く
-- 3. PARTITION BY について
--    - 番号を振り直す単位を指定する。このクエリでは社員ごと
--    - 省略すると全行が 1 つのまとまりになり、全体を通して番号が振られる (補助クエリの 1)
-- 4. ORDER BY (OVER の中) について
--    - まとまりの中で、番号を振る順番を指定する。このクエリでは改定日の新しい順
--    - 省略すると、どの行に何番が振られるかが決まらない
--    - クエリ末尾の ORDER BY (結果の並び順) とは別物

USE window_functions;

SELECT
    sh.employee_id,
    e.name,
    sh.monthly_salary,
    sh.effective_from,
    ROW_NUMBER() OVER (
        PARTITION BY sh.employee_id      -- 社員ごとに番号を振り直す
        ORDER BY sh.effective_from DESC  -- 新しい給与改定日から 1, 2, 3 ... と振る
    ) AS rn
FROM salary_histories AS sh
INNER JOIN employees AS e
    ON e.id = sh.employee_id
ORDER BY sh.employee_id, rn;
