-- 2. OVER の中の PARTITION BY を外すと、社員ごとに番号が振り直されず、全社員の給与改定日を通して新しい順に番号が振られる
--    - ORDER BY は残しているので、給与改定日の新しい順に番号が振られる点は変わらない
--    - rn (ROW_NUMBER で振った番号) は、社員をまたいだ 1〜23 の通し番号になる
--      (例: 佐藤の最新の給与改定日 2025-04-01 は 5、鈴木の 2026-04-01 は 1 になる)
--    - 結果を社員 ID 順に並べているため社員ごとの番号に見えるが、番号自体は全社共通
--    - 同じ給与改定日の行 (2026-04-01 の鈴木・田中・中村) にも別々の番号が振られ、誰が先になるかは決まらない
--    - つまり、rn = 1 になるのは全社で最も新しい給与改定日の 1 行だけで、社員ごとの最新の給与改定日は取れなくなる
--    - 社員ごとに番号を振るには、OVER の中の PARTITION BY で番号を振り直す単位を指定する必要がある
SELECT
    sh.employee_id,
    e.name,
    sh.monthly_salary,
    sh.effective_from,
    ROW_NUMBER() OVER (
        -- PARTITION BY sh.employee_id   -- 社員ごとに番号を振り直す
        ORDER BY sh.effective_from DESC  -- 新しい給与改定日から 1, 2, 3 ... と振る
    ) AS rn
FROM salary_histories AS sh
INNER JOIN employees AS e
    ON e.id = sh.employee_id
ORDER BY sh.employee_id, rn;
