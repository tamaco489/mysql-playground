-- 1. OVER の中の ORDER BY を外すと、社員ごとの番号は振られるが、どの給与改定日に何番が振られるかが決まらない
--    - PARTITION BY は残しているので、社員ごとに 1 から番号が振り直される点は変わらない
--    - rn (ROW_NUMBER で振った番号) の順番が、給与改定日と関係なくなる
--      (例: 佐藤は 2022-04-01 が 1、2025-04-01 が 2 になり、最新の給与改定日が 1 にならない)
--    - 新しい順でも古い順でも、登録した順でもない。MySQL がその時に行を読んだ順で振られる
--    - つまり、データやインデックスが変わると同じクエリでも番号が変わりうるため、rn = 1 が最新の給与改定日だとは言えなくなる
--    - 番号に意味を持たせるには、OVER の中の ORDER BY で振る順番を指定する必要がある
SELECT
    sh.employee_id,
    e.name,
    sh.monthly_salary,
    sh.effective_from,
    ROW_NUMBER() OVER (
        PARTITION BY sh.employee_id         -- 社員ごとに番号を振り直す
        -- ORDER BY sh.effective_from DESC  -- 新しい給与改定日から 1, 2, 3 ... と振る
    ) AS rn
FROM salary_histories AS sh
INNER JOIN employees AS e
    ON e.id = sh.employee_id
ORDER BY sh.employee_id, rn;
