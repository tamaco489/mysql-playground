-- 3. OVER を書き忘れると、構文エラーになる
--    - ROW_NUMBER() は、OVER と組み合わせて初めてウィンドウ関数として動く。単独では使えない
--    - OVER がないと、MySQL は ROW_NUMBER() の後ろの括弧 (PARTITION BY ...) を解釈できず、構文エラー (ERROR 1064) を返す
SELECT
    sh.employee_id,
    e.name,
    sh.monthly_salary,
    sh.effective_from,
    ROW_NUMBER() (                       -- OVER を忘れるとエラーになる
        PARTITION BY sh.employee_id      -- 社員ごとに番号を振り直す
        ORDER BY sh.effective_from DESC  -- 新しい給与改定日から 1, 2, 3 ... と振る
    ) AS rn
FROM salary_histories AS sh
INNER JOIN employees AS e
    ON e.id = sh.employee_id
ORDER BY sh.employee_id, rn;
