-- 社員ごとの最新の給与改定日を求めるクエリ例。
-- GROUP BY で社員ごとの最新の改定日を求め、その改定日の行を給与改定履歴 (salary_histories) から取り出す。
-- 比べる相手: 03_current-salary_with-window.sql
--
-- 給与改定履歴のうち effective_from (改定後の月給適用日) が最も新しい行が現在の月給。
-- 現在の月給は、月給の大きさではなく、改定日の新しさで選ぶ必要がある。
-- 例えば鈴木 (2) は 2026-04 に 400000 から 380000 へ降給しており、
-- MAX(monthly_salary) で月給の最大値を求めると、現在の 380000 ではなく過去の 400000 になってしまう。
-- そのため、このクエリでは MAX(effective_from) で最新の改定日を求めてから、その行の月給を取り出すクエリにしている。

USE window_functions;

-- (1) 社員ごとの最新の改定日を、先に一覧にする
--     社員 1 人につき 1 行になる (例: 鈴木は 3 行の改定履歴から、2026-04-01 の 1 行だけ)
WITH latest AS (
    SELECT
        employee_id,
        MAX(effective_from) AS latest_effective_from  -- 社員ごとに、一番新しい改定日を取る
    FROM salary_histories
    GROUP BY employee_id                              -- 社員ごとに行をまとめる
)
-- (2) 一覧と突き合わせて、改定日が一致する行だけを残す
--     (1) には改定日しか残っていないので、給与改定履歴 (salary_histories) をもう一度読んで月給を取り出す
SELECT
    e.id,
    e.name,
    sh.monthly_salary,
    sh.effective_from
FROM salary_histories AS sh
INNER JOIN latest AS l
    ON l.employee_id = sh.employee_id                -- 同じ社員の行を突き合わせる
    AND l.latest_effective_from = sh.effective_from  -- 最新の改定日の行だけを残す
INNER JOIN employees AS e
    ON e.id = sh.employee_id
ORDER BY e.id;
