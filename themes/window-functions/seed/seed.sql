-- 給与の支給実績 (累計の題材)
-- 2026-01 から 2026-06 まで、毎月 25 日に支給する。
-- 支給額は、支給日の時点で有効な月給にする。2026-04 に改定された社員は、4 月から額が変わる。
INSERT INTO salary_payments (employee_id, amount, paid_on)
WITH RECURSIVE months (paid_on) AS (
    SELECT DATE '2026-01-25'
    UNION ALL
    SELECT paid_on + INTERVAL 1 MONTH FROM months WHERE paid_on < DATE '2026-06-25'
)
SELECT
    e.id,
    (
        SELECT sh.monthly_salary
        FROM salary_histories AS sh
        WHERE sh.employee_id = e.id
            AND sh.effective_from <= m.paid_on
        ORDER BY sh.effective_from DESC
        LIMIT 1
    ),
    m.paid_on
FROM employees AS e
CROSS JOIN months AS m
WHERE e.hired_on <= m.paid_on
ORDER BY e.id, m.paid_on;

